test('G01 [Req 5/3] Excel CSV export: a quoted cell with a comma ("Model S, LR") does not reject the file', () => {
  // This is exactly what Excel / Google Sheets write when a cell contains a comma.
  const csv = `Make,Model,VIN\r\nHonda,Accord,${A}\r\nTesla,"Model S, Long Range",${B}\r\n`;
  const r = V.processText(csv);
  // Actual: invalid_input ('"'): the comma inside quotes shifts the row and the
  // second half of the model lands in the VIN column.
  assert.strictEqual(r.ok, true, `got ${r.error} ${JSON.stringify(r.invalidChars)}`);
  assert.deepStrictEqual(r.vins, [A, B]);
});

test('G01b [Req 5] copy from Excel: a multi-line cell (Alt+Enter) in a notes column does not break the paste', () => {
  // Excel puts quotes around a cell that contains a line break when copying.
  const paste = `VIN\tNotes\n${A}\t"Needs tires\nand brakes"\n${B}\tok\n`;
  const r = V.processText(paste);
  assert.strictEqual(r.ok, true, `got ${r.error} ${JSON.stringify(r.invalidChars)}`);
  assert.deepStrictEqual(r.vins, [A, B]);
});

test('G01c [Req 5/6] copy from Excel (tab-separated): a comma inside a cell ("Smith, John") does not add a fake VIN', () => {
  const paste = `Unit\tDriver\tVIN\n1\tAl\t${A}\n2\tSmith, John\t${B}\n`;
  const r = V.processText(paste);
  // Actual: ["1HG…","JOHN","5YJ…"]; with "Smith, J." the whole paste is rejected.
  assert.deepStrictEqual(r.vins, [A, B]);
  assert.strictEqual(V.processText(paste.replace('Smith, John', 'Smith, J.')).ok, true);
});

